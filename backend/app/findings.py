def trend_findings(table: TypedTable) -> list[dict]:
    dates = [c for c in table.columns if c.kind == "datetime" and len(c.valid) >= 10]
    if not dates:
        return []
    date_col = dates[0]
    measure = main_measure(table)
    if measure is not None:
        ts = time_series(table, date_col.name, measure.name, "sum")
        metric = f"total {measure.name}"
        series = [(p.label, p.value) for p in ts.points]
    else:
        ts = time_series(table, date_col.name)
        metric = "number of records"
        series = [(p.label, float(p.count)) for p in ts.points]

    complete = list(series)
    dropped = []
    if ts.last_period_partial and complete:
        dropped.append(complete.pop()[0])
    if ts.first_period_partial and complete:
        dropped.append(complete.pop(0)[0])
    # Periods with no records have value None for sums: treat as gaps, not zeros.
    usable = [(label, v) for label, v in complete if v is not None]
    if len(usable) < 4:
        return []
    k = max(1, math.ceil(len(usable) / 3))
    first = [v for _, v in usable[:k]]
    last = [v for _, v in usable[-k:]]
    first_avg, last_avg = sum(first) / len(first), sum(last) / len(last)
    if first_avg <= 0:  # % change is undefined or misleading from a zero/negative base
        return []
    change = (last_avg - first_avg) / first_avg
    if abs(change) < TREND_THRESHOLD:
        return []
    direction = "increased" if change > 0 else "decreased"
    period = f"{usable[0][0]} – {usable[-1][0]}"
    caveat = (
        "A rise or fall over time does not show what caused it; seasonality, pricing, or changes in how data "
        "was recorded can all produce trends."
    )
    if dropped:
        caveat += f" Incomplete periods were excluded: {', '.join(dropped)}."
    magnitude = min(1.0, abs(change))
    return [
        dict(
            kind="trend",
            title=f"{metric.capitalize()} {direction} by {abs(change) * 100:.0f}% over the period",
            description=(
                f"Comparing the first {k} with the last {k} complete {ts.granularity} period(s), the average "
                f"{metric} per {ts.granularity} {direction} from {fmt(first_avg)} to {fmt(last_avg)}."
            ),
            evidence=[
                Evidence(
                    label=f"Average of first {k} period(s)",
                    value=fmt(first_avg),
                    calculation=f"mean of {metric} for {', '.join(lbl for lbl, _ in usable[:k])}",
                ),
                Evidence(
                    label=f"Average of last {k} period(s)",
                    value=fmt(last_avg),
                    calculation=f"mean of {metric} for {', '.join(lbl for lbl, _ in usable[-k:])}",
                ),
                Evidence(
                    label="Relative change",
                    value=f"{change * 100:+.1f}%",
                    calculation="(last average − first average) ÷ first average",
                ),
            ],
            columns=[date_col.name] + ([measure.name] if measure else []),
            period=period,
            why_it_matters=f"A sustained change in {metric} can signal growth, decline or a shift in activity worth explaining.",
            caveat=caveat,
            follow_up=f"Which categories or segments drove the change in {metric}?",
            magnitude=magnitude,
        )
    ]


def concentration_findings(table: TypedTable) -> list[dict]:
    measure = main_measure(table)
    use_measure = measure is not None and bool((measure.valid >= 0).all()) and measure.valid.sum() > 0
    out: list[dict] = []
    if table.n_rows < MIN_ROWS_FOR_PATTERNS:
        return out
    for dim in grouping_dimensions(table):
        groups = dim.values.dropna().astype(str)
        if groups.nunique() < 3:
            continue
        if use_measure:
            assert measure is not None
            frame = pd.DataFrame({"g": dim.values, "v": measure.values}).dropna()
            totals = frame.groupby("g")["v"].sum()
            metric = f"total {measure.name}"
        else:
            totals = groups.value_counts()
            metric = "records"
        totals = totals.sort_index().sort_values(ascending=False, kind="mergesort")
        grand = float(totals.sum())
        if grand <= 0:
            continue
        shares = totals / grand * 100
        top_name, top_share = str(shares.index[0]), float(shares.iloc[0])
        cumulative = shares.cumsum()
        needed = int((cumulative < 80).sum()) + 1
        n_groups = len(shares)
        pareto = n_groups >= 5 and needed <= max(1, math.floor(0.2 * n_groups))
        if top_share < CONCENTRATION_TOP_SHARE and not pareto:
            continue
        if top_share >= CONCENTRATION_TOP_SHARE:
            title = f"'{top_name}' accounts for {top_share:.0f}% of {metric}"
            description = (
                f"Across {n_groups} categories of '{dim.name}', '{top_name}' contributes {fmt(float(totals.iloc[0]))} "
                f"of {fmt(grand)} ({top_share:.1f}%)."
            )
            magnitude = top_share / 100
        else:
            title = f"{needed} of {n_groups} '{dim.name}' categories account for 80% of {metric}"
            description = f"{metric.capitalize()} is concentrated: the top {needed} categories reach {float(cumulative.iloc[needed - 1]):.1f}%."
            magnitude = 0.8
        out.append(
            dict(
                kind="concentration",
                title=title,
                description=description,
                evidence=[
                    Evidence(
                        label=f"Share held by '{top_name}'",
                        value=f"{top_share:.1f}%",
                        calculation=f"{metric} for '{top_name}' ÷ overall {metric}",
                    ),
                    Evidence(
                        label="Categories needed to reach 80%",
                        value=f"{needed} of {n_groups}",
                        calculation="categories sorted by contribution, cumulative share",
                    ),
                ],
                columns=[dim.name] + ([measure.name] if use_measure and measure else []),
                why_it_matters="Heavy reliance on a few categories means results are sensitive to changes in those categories.",
                caveat="Concentration describes the data provided; it may reflect how categories are defined rather than underlying performance.",
                follow_up=f"How has the share held by '{top_name}' changed over time?",
                magnitude=magnitude,
            )
        )
    out.sort(key=lambda f: -f["magnitude"])
    return out[:2]


def missing_findings(table: TypedTable, profile: DatasetProfile) -> list[dict]:
    out = []
    for p in profile.column_profiles:
        if p.inferred_type == "empty" or p.missing_pct < MISSING_THRESHOLD:
            continue
        out.append(
            dict(
                kind="missing_data",
                title=f"'{p.name}' is {p.missing_pct:.0f}% missing",
                description=f"{p.missing} of {profile.rows} rows have no value for '{p.name}'.",
                evidence=[
                    Evidence(
                        label="Missing values", value=f"{p.missing} ({p.missing_pct}%)", calculation="blank cells ÷ total rows"
                    )
                ],
                columns=[p.name],
                why_it_matters="Any statistic using this column is based on a subset of rows, which may not represent the whole dataset.",
                caveat="If values are missing for a reason (e.g. only recorded for some cases), averages and totals can be biased.",
                follow_up=f"Why is '{p.name}' missing, and are the missing rows different from the rest?",
                magnitude=min(1.0, p.missing_pct / 60),
            )
        )
    return out


def group_difference_findings(table: TypedTable) -> list[dict]:
    """Compare group averages for every measure x category pair; keep the two largest gaps."""
    out = []
    for measure in analysable_measures(table)[:8]:
        overall_sd = float(measure.valid.std(ddof=1)) if len(measure.valid) >= 2 else 0.0
        if overall_sd == 0:
            continue
        for dim in grouping_dimensions(table):
            frame = pd.DataFrame({"g": dim.values, "v": measure.values}).dropna()
            stats = frame.groupby("g")["v"].agg(["mean", "count"])
            stats = stats[stats["count"] >= 5]
            if len(stats) < 2:
                continue
            stats = stats.sort_index().sort_values("mean", ascending=False, kind="mergesort")
            hi_name, lo_name = str(stats.index[0]), str(stats.index[-1])
            hi, lo = float(stats["mean"].iloc[0]), float(stats["mean"].iloc[-1])
            effect = (hi - lo) / overall_sd
            if effect < GROUP_EFFECT_THRESHOLD:
                continue
            out.append(
                dict(
                    kind="group_difference",
                    title=f"Average {measure.name} differs markedly by {dim.name}",
                    description=(
                        f"'{hi_name}' has the highest average {measure.name} ({fmt(hi)}, n={int(stats['count'].iloc[0])}) and "
                        f"'{lo_name}' the lowest ({fmt(lo)}, n={int(stats['count'].iloc[-1])})."
                    ),
                    evidence=[
                        Evidence(
                            label="Difference in averages",
                            value=fmt(hi - lo),
                            calculation=f"mean('{hi_name}') − mean('{lo_name}')",
                        ),
                        Evidence(
                            label="Difference in standard deviations",
                            value=f"{effect:.2f}",
                            calculation=f"difference ÷ overall SD of {measure.name} ({fmt(overall_sd)})",
                        ),
                        Evidence(label="Groups compared", value=str(len(stats)), calculation="groups with at least 5 values"),
                    ],
                    columns=[dim.name, measure.name],
                    why_it_matters="Large gaps between groups can point to where performance, demand or cost differs most.",
                    caveat="This compares averages only and is not a statistical significance test; groups may differ in size or mix in ways that explain the gap.",
                    follow_up=f"What distinguishes '{hi_name}' from '{lo_name}' beyond {dim.name}?",
                    magnitude=min(1.0, effect / 2),
                )
            )
    out.sort(key=lambda f: -f["magnitude"])
    return out[:2]


def correlation_findings(table: TypedTable) -> list[dict]:
    corr = correlation_matrix(table)
    if corr is None:
        return []
    out = []
    for pair in corr.pairs:
        if abs(pair.r) < CORRELATION_THRESHOLD:
            continue
        direction = "rise together" if pair.r > 0 else "move in opposite directions"
        out.append(
            dict(
                kind="correlation",
                title=f"{pair.strength.capitalize()} association between '{pair.x}' and '{pair.y}'",
                description=f"Across {pair.n} rows, '{pair.x}' and '{pair.y}' tend to {direction} (r = {pair.r:+.2f}).",
                evidence=[
                    Evidence(
                        label="Pearson correlation (r)",
                        value=f"{pair.r:+.3f}",
                        calculation=f"Pearson r on {pair.n} rows where both values are present",
                    )
                ],
                columns=[pair.x, pair.y],
                why_it_matters="Related measures can help explain each other or be used together when planning.",
                caveat="Correlation is not causation. The two columns may also be mechanically linked (for example, one calculated from the other), and r only captures straight-line relationships.",
                follow_up=f"Is there a business reason '{pair.x}' and '{pair.y}' would move together?",
                magnitude=abs(pair.r),
            )
        )
    return out[:3]


def outlier_findings(table: TypedTable) -> list[dict]:
    out = []
    for col in analysable_measures(table):
        s = numeric_summary(col.values)
        o = s.outliers
        if o.count == 0 or o.pct > 10:
            continue
        magnitude = 0.6 if o.extreme_count else 0.3
        examples = ", ".join(fmt(v) for v in o.examples[:3])
        out.append(
            dict(
                kind="outliers",
                title=f"{o.count} potential outlier(s) in '{col.name}'",
                description=f"{o.count} value(s) ({o.pct}%) fall outside {fmt(o.lower_fence)} to {fmt(o.upper_fence)}; the most extreme include {examples}.",
                evidence=[
                    Evidence(
                        label="Typical range (Tukey fences)",
                        value=f"{fmt(o.lower_fence)} to {fmt(o.upper_fence)}",
                        calculation=f"Q1 − 1.5×IQR to Q3 + 1.5×IQR (Q1={fmt(s.q1)}, Q3={fmt(s.q3)})",
                    ),
                    Evidence(label="Values beyond 3×IQR", value=str(o.extreme_count), calculation="extreme values"),
                ],
                columns=[col.name],
                why_it_matters="A few unusual values can pull averages and totals away from what is typical.",
                caveat="Unusual does not mean wrong: these values may be genuine (e.g. a large order). They have not been removed.",
                follow_up=f"Are the largest values in '{col.name}' genuine records or errors?",
                magnitude=magnitude,
            )
        )
    out.sort(key=lambda f: -f["magnitude"])
    return out[:3]


def negative_findings(table: TypedTable) -> list[dict]:
    out = []
    for col in analysable_measures(table):
        v = col.valid
        neg = int((v < 0).sum())
        if neg == 0 or neg > 0.1 * len(v):
            continue
        out.append(
            dict(
                kind="negative_values",
                title=f"'{col.name}' contains {neg} negative value(s)",
                description=f"{neg} of {len(v)} values in '{col.name}' are below zero (lowest {fmt(float(v.min()))}).",
                evidence=[
                    Evidence(label="Negative values", value=f"{neg} ({pct(neg, len(v))}%)", calculation="count of values < 0")
                ],
                columns=[col.name],
                why_it_matters="Negative values reduce totals; if they are refunds or corrections that may be correct, if they are errors totals are understated.",
                caveat="Negative values were kept in all calculations.",
                follow_up=f"What do the negative '{col.name}' values represent?",
                magnitude=0.5,
            )
        )
    return out[:2]


def duplicate_findings(profile: DatasetProfile) -> list[dict]:
    if profile.duplicate_pct < DUPLICATE_THRESHOLD:
        return []
    return [
        dict(
            kind="duplicates",
            title=f"{profile.duplicate_rows} duplicate row(s) found",
            description=f"{profile.duplicate_pct}% of rows exactly repeat an earlier row.",
            evidence=[
                Evidence(
                    label="Duplicate rows",
                    value=f"{profile.duplicate_rows} ({profile.duplicate_pct}%)",
                    calculation="rows identical in every column to an earlier row",
                )
            ],
            columns=[],
            why_it_matters="If duplicates are double entries, totals and counts are overstated.",
            caveat="Duplicates have not been removed; some datasets legitimately contain identical rows.",
            follow_up="Are the duplicated rows genuine repeat events or data-entry errors?",
            magnitude=min(1.0, profile.duplicate_pct / 10),
        )
    ]


# --------------------------------------------------------------------------- #
# Engine
# --------------------------------------------------------------------------- #


def build_findings(table: TypedTable, profile: DatasetProfile) -> FindingsResult:
    raw: list[dict] = []
    raw += trend_findings(table)
    raw += concentration_findings(table)
    raw += group_difference_findings(table)
    raw += correlation_findings(table)
    raw += missing_findings(table, profile)
    raw += duplicate_findings(profile)
    raw += outlier_findings(table)
    raw += negative_findings(table)

    kind_order = list(RULES)
    for f in raw:
        f["score"] = _score(f["kind"], f["magnitude"])
        f["strength"] = _strength(f["magnitude"])
    raw.sort(key=lambda f: (-f["score"], kind_order.index(f["kind"])))

    findings = []
    for i, f in enumerate(raw, start=1):
        f.pop("magnitude")
        findings.append(Finding(id=f"F{i}", **f))

    message = None
    if not findings:
        message = (
            "No patterns met the documented thresholds. This is a valid result: the dataset may be too small, "
            "too uniform, or lack the date/category/numeric columns the rules need. No insights have been invented."
        )
    ranking = [
        "score = weight(kind) × magnitude × 100",
        *[f"{kind}: weight {w}; triggered when {thr}; magnitude = {mag}" for kind, (w, thr, mag) in RULES.items()],
    ]
    return FindingsResult(findings=findings, message=message, ranking_method=ranking)


