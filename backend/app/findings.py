"""Deterministic findings engine.

Each rule below looks for one kind of pattern, using fixed thresholds. A rule
only produces a finding when its threshold is met, and every finding carries
the numbers that triggered it. Nothing here is generated by AI.

Ranking (documented in docs/methodology.md):

    score = weight(kind) x magnitude x 100      (0-100)

`weight` reflects how decision-relevant that kind of pattern usually is;
`magnitude` (0-1) reflects how strong this particular instance is. Both are
listed in RULES so the ranking is fully explainable.

Language rules: findings describe what the data shows. Correlations are
"associations", unusual values are "potential outliers", and every finding
carries a caveat. No finding claims a cause.
"""

from __future__ import annotations

import math

import pandas as pd

from .analysis import (
    analysable_measures,
    correlation_matrix,
    grouping_dimensions,
    main_measure,
    numeric_summary,
    pct,
    time_series,
)
from .inference import TypedTable
from .schemas import DatasetProfile, Evidence, Finding, FindingsResult

# kind: (weight, threshold description, magnitude description)
RULES: dict[str, tuple[float, str, str]] = {
    "trend": (
        0.9,
        "average of the last third of complete periods differs from the first third by >= 20%",
        "min(1, |% change| / 100)",
    ),
    "concentration": (
        0.8,
        "one category holds >= 40% of the total, or <= 20% of categories hold >= 80% (needs >= 3 categories)",
        "top category share (0-1), or 0.8 for a Pareto pattern",
    ),
    "missing_data": (0.7, "a column is >= 20% missing", "min(1, % missing / 60)"),
    "group_difference": (
        0.7,
        "highest vs lowest group average differ by >= 0.8 standard deviations (groups with >= 5 values)",
        "min(1, difference in SDs / 2)",
    ),
    "correlation": (0.6, "|Pearson r| >= 0.5 with >= 10 pairs", "|r|"),
    "duplicates": (0.6, ">= 1% of rows are exact duplicates", "min(1, % duplicated / 10)"),
    "outliers": (
        0.5,
        "values beyond 1.5 x IQR exist and make up <= 10% of the column",
        "0.6 if any value is beyond 3 x IQR, else 0.3",
    ),
    "negative_values": (0.4, "a mostly-positive measure (>= 90% non-negative) has negative values", "0.5"),
}

TREND_THRESHOLD = 0.20
CONCENTRATION_TOP_SHARE = 40.0
MISSING_THRESHOLD = 20.0
GROUP_EFFECT_THRESHOLD = 0.8
CORRELATION_THRESHOLD = 0.5
DUPLICATE_THRESHOLD = 1.0
MIN_ROWS_FOR_PATTERNS = 10  # below this, shares and group comparisons are too fragile to report


def fmt(value: float | None, digits: int = 2) -> str:
    if value is None or (isinstance(value, float) and not math.isfinite(value)):
        return "n/a"
    if abs(value) >= 1000 or float(value).is_integer():
        return f"{value:,.0f}" if float(value).is_integer() else f"{value:,.{digits}f}"
    return f"{value:,.{digits}f}"


def _score(kind: str, magnitude: float) -> float:
    return round(RULES[kind][0] * max(0.0, min(1.0, magnitude)) * 100, 1)


def _strength(magnitude: float) -> str:
    return "strong" if magnitude >= 0.66 else "moderate" if magnitude >= 0.33 else "weak"


