EXPORT_TABLES = (
    "column_profile",
    "data_issues",
    "findings",
    "numeric_summary",
    "category_frequencies",
    "grouped_summary",
    "time_series",
    "correlations",
)

_FORMULA_PREFIXES = ("=", "+", "-", "@", "\t", "\r")


def csv_safe(value: Any) -> Any:
    """Prevent spreadsheet formula injection when a CSV is opened in Excel.

    Text cells starting with = + - @ are prefixed with an apostrophe. Real
    numbers (including negatives) are left untouched.
    """
    if isinstance(value, str) and value.startswith(_FORMULA_PREFIXES):
        return "'" + value
    return value


def _write(header: list[str], rows: list[list[Any]]) -> str:
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow([csv_safe(h) for h in header])
    for r in rows:
        w.writerow([csv_safe("" if v is None else v) for v in r])
    return buf.getvalue()


def export_csv(table: str, profile: DatasetProfile, analysis: AnalysisBundle, findings: FindingsResult) -> str:
    if table == "column_profile":
        return _write(
            [
                "column",
                "type",
                "role",
                "non_missing",
                "missing",
                "missing_pct",
                "invalid",
                "unique",
                "is_constant",
                "likely_identifier",
            ],
            [
                [
                    c.name,
                    c.inferred_type,
                    c.role,
                    c.non_missing,
                    c.missing,
                    c.missing_pct,
                    c.invalid,
                    c.unique,
                    c.is_constant,
                    c.likely_identifier,
                ]
                for c in profile.column_profiles
            ],
        )
    if table == "data_issues":
        return _write(
            ["id", "severity", "category", "column", "count", "message"],
            [[i.id, i.severity, i.category, i.column, i.count, i.message] for i in profile.issues],
        )
    if table == "findings":
        return _write(
            [
                "id",
                "score",
                "strength",
                "kind",
                "title",
                "description",
                "evidence",
                "columns",
                "period",
                "why_it_matters",
                "caveat",
                "follow_up",
            ],
            [
                [
                    f.id,
                    f.score,
                    f.strength,
                    f.kind,
                    f.title,
                    f.description,
                    "; ".join(f"{e.label}: {e.value} ({e.calculation})" for e in f.evidence),
                    ", ".join(f.columns),
                    f.period,
                    f.why_it_matters,
                    f.caveat,
                    f.follow_up,
                ]
                for f in findings.findings
            ],
        )
    if table == "numeric_summary":
        return _write(
            [
                "column",
                "count",
                "mean",
                "median",
                "std",
                "min",
                "q1",
                "q3",
                "max",
                "sum",
                "negatives",
                "zeros",
                "outliers_iqr",
                "lower_fence",
                "upper_fence",
            ],
            [
                [
                    n.column,
                    s.count,
                    s.mean,
                    s.median,
                    s.std,
                    s.min,
                    s.q1,
                    s.q3,
                    s.max,
                    s.sum,
                    s.negatives,
                    s.zeros,
                    s.outliers.count,
                    s.outliers.lower_fence,
                    s.outliers.upper_fence,
                ]
                for n in analysis.numeric
                for s in [n.summary]
            ],
        )
    if table == "category_frequencies":
        rows = []
        for c in analysis.categorical:
            rows += [[c.column, r.value, r.count, r.pct] for r in c.rows]
            if c.other_count:
                rows.append(
                    [
                        c.column,
                        f"Other ({c.other_categories} categories)",
                        c.other_count,
                        round(100 * c.other_count / c.non_missing, 2),
                    ]
                )
        return _write(["column", "value", "count", "pct_of_non_missing"], rows)
    if table == "grouped_summary":
        g = analysis.default_grouped
        if g is None:
            raise AppError(404, "export_unavailable", "No grouped summary is available for this dataset.")
        return _write(
            [
                g.category_column,
                f"count_{g.value_column}",
                f"mean_{g.value_column}",
                f"median_{g.value_column}",
                f"sum_{g.value_column}",
                "share_of_total_pct",
            ],
            [[r.group, r.count, r.mean, r.median, r.sum, r.share_of_total] for r in g.rows],
        )
    if table == "time_series":
        ts = analysis.default_timeseries
        if ts is None:
            raise AppError(404, "export_unavailable", "No date column is available for a time series.")
        value_header = f"{ts.agg}_{ts.value_column}" if ts.value_column else "value"
        return _write(
            ["period_start", "label", "records", value_header], [[p.period, p.label, p.count, p.value] for p in ts.points]
        )
    if table == "correlations":
        if analysis.correlation is None:
            raise AppError(404, "export_unavailable", "Correlation needs at least two numeric columns.")
        return _write(
            ["x", "y", "pearson_r", "n_pairs", "strength"], [[p.x, p.y, p.r, p.n, p.strength] for p in analysis.correlation.pairs]
        )
    raise AppError(404, "unknown_export", f"Unknown export '{table}'. Available: {', '.join(EXPORT_TABLES)}.")
