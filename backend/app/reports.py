"""Structured report built only from computed results, plus HTML and CSV export.

The report is assembled from the same profile, analysis and findings objects
the app displays, so the export cannot drift from what the user saw. There is
no placeholder text: a section with nothing to say says so explicitly.
"""

from __future__ import annotations

import csv
import io
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from jinja2 import Environment, FileSystemLoader, select_autoescape

from .charts_svg import bar_chart, compact, line_chart
from .errors import AppError
from .findings import fmt
from .schemas import AIExplanation, AnalysisBundle, DatasetProfile, FindingsResult

METHODOLOGY = [
    "Every cell was read as text first; types (number, date, category, text) were inferred when at least 95% of a column's values fit the type. Values that did not fit were counted as invalid and excluded, never replaced with zero.",
    "Blank cells and common placeholders (NA, N/A, null, none, -) are treated as missing. Missing values are excluded from each calculation; the number of values used is reported.",
    "Ambiguous dates such as 03/04/2025 are read day-first (UK convention). Dates with time-zone offsets are converted to UTC.",
    "Quartiles use linear interpolation (equivalent to Excel QUARTILE.INC); standard deviation is the sample standard deviation (n−1).",
    "Potential outliers use Tukey's fences: values below Q1 − 1.5×IQR or above Q3 + 1.5×IQR. Outliers are flagged, not removed.",
    "Correlation is Pearson's r, calculated only where at least 10 rows have both values present.",
    "Duplicate rows are rows identical in every column to an earlier row. They are counted, not removed.",
    "Findings are produced by fixed, documented rules and ranked by score = weight × magnitude × 100. No finding is generated by AI.",
]

_TEMPLATES = Path(__file__).parent / "templates"
_env = Environment(loader=FileSystemLoader(_TEMPLATES), autoescape=select_autoescape(["html", "j2"]))


def build_report(
    *,
    filename: str,
    sheet: str | None,
    is_demo: bool,
    loaded_at: datetime,
    profile: DatasetProfile,
    analysis: AnalysisBundle,
    findings: FindingsResult,
    ai: AIExplanation | None = None,
    main_measure_name: str | None = None,
) -> dict[str, Any]:
    generated = datetime.now(UTC).replace(microsecond=0)
    confirmed = [i for i in profile.issues if i.severity == "confirmed"]
    potential = [i for i in profile.issues if i.severity == "potential"]

    charts = []
    ts = analysis.default_timeseries
    if ts and ts.points:
        values = [p.value if ts.agg != "count" else float(p.count) for p in ts.points]
        label = f"{ts.agg} of {ts.value_column}" if ts.value_column else "records"
        caption = f"{label.capitalize()} per {ts.granularity} by '{ts.date_column}'."
        if ts.first_period_partial or ts.last_period_partial:
            caption += " The first and/or last period is incomplete, so it may look lower than it really was."
        charts.append(
            {
                "title": f"{label.capitalize()} over time",
                "svg": line_chart(label, [p.label for p in ts.points], values, label),
                "caption": caption,
            }
        )
    g = analysis.default_grouped
    if g and g.rows:
        metric = "sum" if g.shares_valid else "mean"
        vals = [r.sum if metric == "sum" else r.mean for r in g.rows]
        charts.append(
            {
                "title": f"{metric.capitalize()} of {g.value_column} by {g.category_column}",
                "svg": bar_chart(
                    f"{metric} of {g.value_column}", [r.group for r in g.rows], vals, f"{metric} of {g.value_column}"
                ),
                "caption": g.note or f"{len(g.rows)} groups shown, largest first.",
            }
        )
    if main_measure_name:
        num = next((n for n in analysis.numeric if n.column == main_measure_name), None)
        if num and num.histogram:
            charts.append(
                {
                    "title": f"Distribution of {num.column}",
                    "svg": bar_chart(
                        f"distribution of {num.column}",
                        [f"{compact(b.start)}–{compact(b.end)}" for b in num.histogram],
                        [float(b.count) for b in num.histogram],
                        "number of rows",
                    ),
                    "caption": f"Histogram of {num.summary.count} values in {len(num.histogram)} equal-width bins.",
                }
            )

    limitations = [
        "This report describes the uploaded data only. It cannot account for information that is not in the file.",
        "Findings are descriptive. Statements under 'Why it may matter' are interpretations that need business context to confirm.",
        "No statistical significance testing was performed; differences and correlations may arise by chance, especially in small groups.",
        "Correlation does not imply causation.",
    ]
    if any(i.category == "missing" for i in confirmed):
        limitations.append(
            "Some columns have missing values; statistics for those columns use only the rows where a value is present."
        )
    if profile.duplicate_rows:
        limitations.append(f"{profile.duplicate_rows} duplicate row(s) were kept in all calculations.")
    if ts and (ts.first_period_partial or ts.last_period_partial):
        limitations.append("The time series starts and/or ends part-way through a period.")
    if is_demo:
        limitations.insert(0, "This report was generated from a built-in synthetic DEMO dataset. All records are fictional.")

    next_steps: list[str] = []
    if confirmed:
        next_steps.append(f"Resolve the {len(confirmed)} confirmed data-quality issue(s) at source, then re-run the analysis.")
    for f in findings.findings[:5]:
        next_steps.append(f"{f.follow_up} (from {f.id})")
    if not next_steps:
        next_steps.append("Add more rows, a date column or category columns to enable trend and group comparisons.")

    numeric_rows = [
        {
            "column": n.column,
            "count": n.summary.count,
            "mean": fmt(n.summary.mean),
            "median": fmt(n.summary.median),
            "std": fmt(n.summary.std),
            "min": fmt(n.summary.min),
            "max": fmt(n.summary.max),
            "outliers": n.summary.outliers.count,
        }
        for n in analysis.numeric
    ]

    return {
        "title": f"Data analysis report: {filename}",
        "filename": filename,
        "sheet": sheet,
        "is_demo": is_demo,
        "loaded_at": loaded_at.strftime("%d %b %Y, %H:%M"),
        "generated_at": generated.strftime("%d %b %Y, %H:%M"),
        "generated_at_iso": generated.isoformat(),
        "overview": {
            "rows": profile.rows,
            "columns": profile.columns,
            "type_counts": profile.type_counts,
            "missing_cells_pct": profile.missing_cells_pct,
            "duplicate_rows": profile.duplicate_rows,
            "column_table": [
                {
                    "name": c.name,
                    "type": c.inferred_type,
                    "role": c.role,
                    "missing_pct": c.missing_pct,
                    "unique": c.unique,
                }
                for c in profile.column_profiles
            ],
        },
        "quality": {"confirmed": confirmed, "potential": potential, "parse_notes": profile.parse_notes},
        "methodology": METHODOLOGY,
        "ranking": findings.ranking_method,
        "key_stats": {"numeric": numeric_rows, "categorical": analysis.categorical[:6]},
        "correlations": analysis.correlation.pairs[:8] if analysis.correlation else [],
        "charts": charts,
        "findings": findings.findings,
        "findings_message": findings.message,
        "limitations": limitations,
        "next_steps": next_steps,
        "ai": ai,
    }


def render_html(report: dict[str, Any]) -> str:
    return _env.get_template("report.html.j2").render(**report)


